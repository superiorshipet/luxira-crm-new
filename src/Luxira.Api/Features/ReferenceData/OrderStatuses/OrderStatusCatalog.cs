    private static OrderStatusResponse[] Create(
        params (int Id, string Name)[] statuses) =>
        [.. statuses.Select(status =>
            new OrderStatusResponse(
                status.Id,
                status.Name,
                GetIconUrl(status.Id)))];

    private static string GetIconUrl(int statusId) => statusId switch
    {
        0 or 2 => "/static/blue.svg",
        3 or 4 or 12 or 32 => "/static/yellow.svg",
        5 or 6 or 13 or 14 => "/static/green.svg",
        18 or 25 or 26 or 27 or 28 or 29 or 31 => "/static/white-blue.svg",
        _ => "/static/red.svg",
    };
