    internal static string[] GetDistinctCities(IEnumerable<int>? countryIds)
    {
        if (countryIds is null)
        {
            return [];
        }

        var cities = new List<string>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var countryId in countryIds)
        {
            if (!ByCountry.TryGetValue(countryId, out var countryCities))
            {
                continue;
            }

            foreach (var city in countryCities)
            {
                if (seen.Add(city))
                {
                    cities.Add(city);
                }
            }
        }

        return [.. cities];
    }
